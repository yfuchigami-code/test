    s = prs.slides.add_slide(L2)
    P.set_title(s, title)
    P.lead(s, lead_text)
    s.shapes.add_picture(os.path.join(CH, png), IMG_LEFT, IMG_TOP, width=IMG_W)
    P.note(s, note_text)
    return s


